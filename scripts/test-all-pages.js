const http = require('http');
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const PORT = 4150;
const ROOT_DIR = path.resolve(__dirname, '..');

const mimeTypes = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.json': 'application/json',
};

const server = http.createServer((req, res) => {
  let reqPath = decodeURI(req.url.split('?')[0]);
  if (reqPath === '/' || reqPath === '') reqPath = '/index.html';
  const filePath = path.join(ROOT_DIR, reqPath);

  if (!fs.existsSync(filePath) || fs.statSync(filePath).isDirectory()) {
    res.writeHead(404, { 'Content-Type': 'text/plain' });
    res.end('Not Found: ' + reqPath);
    return;
  }

  const ext = path.extname(filePath).toLowerCase();
  const contentType = mimeTypes[ext] || 'application/octet-stream';
  res.writeHead(200, { 'Content-Type': contentType });
  fs.createReadStream(filePath).pipe(res);
});

// Discover pages dynamically
const PAGES = fs.readdirSync(ROOT_DIR).filter(f => f.endsWith('.html')).sort();

async function runComprehensiveTests() {
  console.log('=====================================================');
  console.log(' HASEENTECH REBUILD — HEADER, FOOTER & FULL AUDIT    ');
  console.log('=====================================================\n');

  let failures = [];
  function assert(condition, message) {
    if (!condition) {
      console.error(`  [FAIL] ${message}`);
      failures.push(message);
    } else {
      console.log(`  [PASS] ${message}`);
    }
  }

  await new Promise(resolve => server.listen(PORT, resolve));
  console.log(`Test web server running at http://localhost:${PORT}`);
  console.log(`Auditing dynamically discovered pages (${PAGES.length} total):\n  ${PAGES.join(', ')}\n`);

  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext();
  const page = await context.newPage();

  const consoleErrors = [];
  page.on('console', msg => {
    if (msg.type() === 'error') {
      consoleErrors.push(`[${page.url()}] ${msg.text()}`);
    }
  });

  const failedRequests = [];
  page.on('requestfailed', request => {
    failedRequests.push(`${request.method()} ${request.url()} - ${request.failure()?.errorText}`);
  });

  try {
    // -------------------------------------------------------------
    // TEST SUITE 1: 17 PAGES INTEGRITY, RESPONSIVENESS & ZERO OVERFLOW
    // -------------------------------------------------------------
    console.log(`--- TEST SUITE 1: ${PAGES.length} PAGES INTEGRITY & 6-VIEWPORT RESPONSIVENESS ---`);
    const viewports = [
      { name: 'Mobile Mini (320px)', width: 320, height: 568 },
      { name: 'Mobile Standard (375px)', width: 375, height: 667 },
      { name: 'Mobile Large (430px)', width: 430, height: 932 },
      { name: 'Tablet (768px)', width: 768, height: 1024 },
      { name: 'Desktop Small (1024px)', width: 1024, height: 768 },
      { name: 'Desktop Large (1440px)', width: 1440, height: 900 }
    ];

    for (const pageName of PAGES) {
      const url = `http://localhost:${PORT}/${pageName}`;
      const res = await page.goto(url, { waitUntil: 'networkidle' });
      assert(res && res.status() === 200, `${pageName} loaded with HTTP 200`);

      const title = await page.title();
      assert(title && title.includes('HaseenTech'), `${pageName} has valid brand title: "${title}"`);

      // Verify current year generated by JS in footer
      const yearText = await page.$eval('#current-year', el => el.textContent.trim());
      assert(yearText === new Date().getFullYear().toString(), `${pageName} footer displays current year: ${yearText}`);

      // Verify 4-column footer structure
      const hasColBrand = await page.$eval('.footer-col-brand', el => el !== null);
      const hasColServices = await page.$eval('.footer-col-services', el => el !== null);
      const hasColCompany = await page.$eval('.footer-col-company', el => el !== null);
      const hasColContact = await page.$eval('.footer-col-contact', el => el !== null);
      assert(hasColBrand && hasColServices && hasColCompany && hasColContact, `${pageName} contains all 4 standardized footer columns`);

      // Check horizontal overflow across all 6 viewports
      for (const vp of viewports) {
        await page.setViewportSize({ width: vp.width, height: vp.height });
        const hasOverflow = await page.evaluate(() => {
          return document.documentElement.scrollWidth > window.innerWidth;
        });
        assert(!hasOverflow, `${pageName} has NO horizontal overflow at ${vp.name}`);
      }
    }

    assert(consoleErrors.length === 0, `0 console errors across all pages (errors: ${consoleErrors.join(', ')})`);
    assert(failedRequests.length === 0, `0 broken assets / failed requests (failed: ${failedRequests.join(', ')})`);

    // -------------------------------------------------------------
    // TEST SUITE 2: SHARED NAVIGATION, DROPDOWNS & KEYBOARD ACCESSIBILITY
    // -------------------------------------------------------------
    console.log('\n--- TEST SUITE 2: SHARED NAVIGATION & KEYBOARD ACCESSIBILITY ---');
    await page.goto(`http://localhost:${PORT}/index.html`);
    await page.setViewportSize({ width: 1440, height: 900 });

    // Desktop nav visible
    const isDesktopNavVisible = await page.$eval('.nav-desktop', el => window.getComputedStyle(el).display !== 'none');
    assert(isDesktopNavVisible, 'Desktop navigation is visible at 1440px');

    // Header CTA button exists and is consistent
    const headerCtaText = await page.$eval('.header-actions a.btn-primary', el => el.textContent.trim());
    const headerCtaHref = await page.$eval('.header-actions a.btn-primary', el => el.getAttribute('href'));
    assert(headerCtaText === 'Start a Project ↗' && headerCtaHref === 'contact.html', 'Header CTA button is consistently "Start a Project ↗" -> contact.html');

    // Status pill visible at desktop
    const statusPillVisible = await page.$eval('.status-indicator-header', el => window.getComputedStyle(el).display !== 'none');
    assert(statusPillVisible, 'Status indicator pill is visible on desktop header');

    // Dropdown toggle via click
    const dropdownToggle = await page.$('.dropdown-trigger');
    await dropdownToggle.click();
    let isDropdownOpen = await page.$eval('.nav-item-dropdown', el => el.classList.contains('open'));
    assert(isDropdownOpen, 'Services dropdown opens on click');

    // Dropdown close on Escape
    await page.keyboard.press('Escape');
    let isDropdownClosed = await page.$eval('.nav-item-dropdown', el => !el.classList.contains('open'));
    assert(isDropdownClosed, 'Services dropdown closes on Escape key');

    // -------------------------------------------------------------
    // TEST SUITE 3: MOBILE DRAWER AT 320px, 375px, 430px
    // -------------------------------------------------------------
    console.log('\n--- TEST SUITE 3: MOBILE DRAWER ACCESSIBILITY & VIEWPORTS ---');
    for (const width of [320, 375, 430]) {
      await page.setViewportSize({ width, height: 700 });
      await page.goto(`http://localhost:${PORT}/index.html`);

      // Toggle drawer
      await page.click('#menu-toggle');
      let isDrawerOpen = await page.$eval('#mobile-drawer', el => el.classList.contains('open'));
      let ariaExpanded = await page.$eval('#menu-toggle', el => el.getAttribute('aria-expanded'));
      let bodyOverflow = await page.evaluate(() => document.body.style.overflow);
      assert(isDrawerOpen && ariaExpanded === 'true' && bodyOverflow === 'hidden', `Mobile drawer opens at ${width}px with scroll lock`);

      // Check drawer elements fit viewport
      const drawerOverflow = await page.evaluate(() => {
        const d = document.getElementById('mobile-drawer');
        return d.scrollWidth > window.innerWidth;
      });
      assert(!drawerOverflow, `Mobile drawer fits cleanly without overflow at ${width}px`);

      // Close on Escape
      await page.keyboard.press('Escape');
      let isDrawerClosed = await page.$eval('#mobile-drawer', el => !el.classList.contains('open'));
      let bodyOverflowRestored = await page.evaluate(() => document.body.style.overflow);
      assert(isDrawerClosed && bodyOverflowRestored === '', `Mobile drawer closes on Escape at ${width}px and restores body scroll`);
    }

    // Drawer links close drawer on click
    await page.setViewportSize({ width: 375, height: 700 });
    await page.click('#menu-toggle');
    await page.click('#mobile-drawer a[href="services.html"]');
    const drawerClosedAfterClick = await page.$eval('#mobile-drawer', el => !el.classList.contains('open'));
    assert(drawerClosedAfterClick, 'Mobile drawer automatically closes when link is clicked');

    // -------------------------------------------------------------
    // TEST SUITE 4: PORTFOLIO & ATELIER RIEBER VERIFICATION
    // -------------------------------------------------------------
    console.log('\n--- TEST SUITE 4: PORTFOLIO FILTERING & CASE STUDIES ---');
    await page.goto(`http://localhost:${PORT}/portfolio.html`);
    const totalProjects = await page.$$eval('.portfolio-card-item', els => els.length);
    assert(totalProjects === 8, `8 real verified projects found in portfolio (count: ${totalProjects})`);

    // Atelier Rieber card & live URL
    const atelierCardExists = await page.$eval('#atelier-rieber', el => el !== null);
    assert(atelierCardExists, 'Atelier Rieber project card exists with id #atelier-rieber');
    const atelierLiveLink = await page.$eval('#atelier-rieber a[href*="atelier-rieber.de"]', el => el.getAttribute('href'));
    assert(atelierLiveLink === 'https://atelier-rieber.de/', `Atelier Rieber live link is verified: ${atelierLiveLink}`);

    // Aqua Seafood card & live URL
    const aquaCardExists = await page.$eval('#aquaseafood', el => el !== null);
    assert(aquaCardExists, 'Aqua Seafood project card exists with id #aquaseafood');
    const aquaLiveLink = await page.$eval('#aquaseafood a[href*="aquaseafood.co.uk"]', el => el.getAttribute('href'));
    assert(aquaLiveLink === 'https://www.aquaseafood.co.uk/', `Aqua Seafood live link is verified: ${aquaLiveLink}`);

    // IFKK Pakistan card & live URL
    const ifkkCardExists = await page.$eval('#ifkkpakistan', el => el !== null);
    assert(ifkkCardExists, 'IFKK Pakistan project card exists with id #ifkkpakistan');
    const ifkkLiveLink = await page.$eval('#ifkkpakistan a[href*="ifkkpakistan.com"]', el => el.getAttribute('href'));
    assert(ifkkLiveLink === 'https://ifkkpakistan.com/', `IFKK Pakistan live link is verified: ${ifkkLiveLink}`);

    // Business filter: 5 projects
    await page.click('button[data-filter="business"]');
    let visibleBusiness = await page.$$eval('.portfolio-card-item', els => els.filter(e => e.style.display !== 'none').length);
    assert(visibleBusiness === 5, `5 business projects visible under Business filter (count: ${visibleBusiness})`);

    // International filter: 3 projects
    await page.click('button[data-filter="international"]');
    let visibleInternational = await page.$$eval('.portfolio-card-item', els => els.filter(e => e.style.display !== 'none').length);
    assert(visibleInternational === 3, `3 international projects visible under International filter (count: ${visibleInternational})`);

    // E-Commerce filter: 1 project
    await page.click('button[data-filter="ecommerce"]');
    let visibleEcommerce = await page.$$eval('.portfolio-card-item', els => els.filter(e => e.style.display !== 'none').length);
    assert(visibleEcommerce === 1, `1 e-commerce project visible under E-Commerce filter (count: ${visibleEcommerce})`);

    // All filter: 8 projects
    await page.click('button[data-filter="all"]');
    let visibleAll = await page.$$eval('.portfolio-card-item', els => els.filter(e => e.style.display !== 'none').length);
    assert(visibleAll === 8, `All 8 projects visible under All filter`);

    // -------------------------------------------------------------
    // TEST SUITE 5: COUNTRY PRICING LOGIC ACROSS MARKETS
    // -------------------------------------------------------------
    console.log('\n--- TEST SUITE 5: COUNTRY-AWARE PRICING SYSTEM ---');
    await page.goto(`http://localhost:${PORT}/pricing.html`);

    let usWordpress = await page.$eval('[data-rate="wordpress"]', el => el.textContent.trim());
    let usCustomWeb = await page.$eval('[data-rate="customWeb"]', el => el.textContent.trim());
    assert(usWordpress === '399' && usCustomWeb === '1,200', `USA starting web rates: WordPress $399 / Custom Web $1,200`);

    // UK
    await page.selectOption('#country-select', 'GB');
    let ukSymbol = await page.$eval('.pricing-currency-sym', el => el.textContent.trim());
    let ukWordpress = await page.$eval('[data-rate="wordpress"]', el => el.textContent.trim());
    assert(ukSymbol === '£' && ukWordpress === '329', `UK proposal verified: £329`);

    // EU
    await page.selectOption('#country-select', 'EU');
    let euSymbol = await page.$eval('.pricing-currency-sym', el => el.textContent.trim());
    let euWordpress = await page.$eval('[data-rate="wordpress"]', el => el.textContent.trim());
    assert(euSymbol === '€' && euWordpress === '369', `EU proposal verified: €369`);

    // Pakistan
    await page.selectOption('#country-select', 'PK');
    let pkSymbol = await page.$eval('.pricing-currency-sym', el => el.textContent.trim());
    let pkWordpress = await page.$eval('[data-rate="wordpress"]', el => el.textContent.trim());
    let pkCustomWeb = await page.$eval('[data-rate="customWeb"]', el => el.textContent.trim());
    assert(pkSymbol === 'PKR' && pkWordpress === '50,000' && pkCustomWeb === '150,000', `Pakistan proposals verified: PKR 50,000 / PKR 150,000`);

    // -------------------------------------------------------------
    // TEST SUITE 6: CONTACT INQUIRY VALIDATION & DISPATCH
    // -------------------------------------------------------------
    console.log('\n--- TEST SUITE 6: CONTACT INQUIRY VALIDATION & DISPATCH ---');
    await page.goto(`http://localhost:${PORT}/contact.html?service=custom-web`);
    let preselectedCustomWeb = await page.$eval('#contact-service', el => el.value);
    assert(preselectedCustomWeb === 'custom-web', 'URL param ?service=custom-web pre-selects Custom Web Development');

    // Empty validation
    await page.click('#btn-submit-inquiry');
    const hasError = await page.$eval('.form-group-modern.has-error', el => el !== null);
    assert(hasError, 'Empty form submission displays inline errors');

    // Valid submission
    await page.fill('#contact-name', 'Alexander Wright');
    await page.fill('#contact-email', 'alexander@wright-advisory.co.uk');
    await page.fill('#contact-country', 'United Kingdom');
    await page.selectOption('#contact-service', 'wordpress');
    await page.fill('#contact-message', 'We need a full WordPress and Elementor website redesign for our management consulting firm in London.');
    await page.click('#btn-submit-inquiry');

    const isSuccessVisible = await page.$eval('#form-status-message.success', el => window.getComputedStyle(el).display !== 'none');
    assert(isSuccessVisible, 'Valid form submission displays transparent brief preparation box');

  } catch (err) {
    console.error('Test execution error:', err);
    failures.push('Exception: ' + err.message);
  } finally {
    await browser.close();
    server.close();
  }

  console.log('\n=====================================================');
  if (failures.length === 0) {
    console.log(' ALL AUDIT & REGRESSION TESTS PASSED WITH 0 FAILURES! ');
    console.log('=====================================================');
    process.exit(0);
  } else {
    console.error(` TEST SUITE FAILED with ${failures.length} errors:`);
    failures.forEach(f => console.error(`  - ${f}`));
    process.exit(1);
  }
}

runComprehensiveTests();
